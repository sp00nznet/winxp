#!/usr/bin/env python3
"""Catalog and lift a set of Windows 2000 modules into one host's generated C.

    py -3 tools/lift.py winmine work/sys/winmine.exe
    py -3 tools/lift.py cmd work/rebased/cmd.exe work/rebased/kernel32.dll work/rebased/ntdll.dll

Every module is catalogued with pcrecomp's disasm32 (exports are seeds) into
work/cat/<file>.functions.json (skipped when there), lifted with drive32 into
src/gen/<name>/<file-stem>/, and one dispatch table over all of them is written
to src/gen/<name>/. Modules must not overlap: rebase first (tools/rebase.py).
"""
import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PCR = os.environ.get('PCRECOMP', os.path.join(ROOT, '..', 'pcrecomp'))
TOOLS = os.path.join(PCR, 'tools')
sys.path[:0] = [os.path.join(TOOLS, 'lift'), os.path.join(TOOLS, 'pe')]
from drive32 import lift_image  # noqa: E402


def put(path, text):
    if not os.path.exists(path) or open(path, newline='').read() != text:
        with open(path, 'w', newline='\n') as f:
            f.write(text)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    name, mods = sys.argv[1], sys.argv[2:]
    out = os.path.join(ROOT, 'src', 'gen', name)
    # A catalog per build: the same file name is different code in another build.
    cat_dir = os.path.join(ROOT, 'work', 'cat' if name == 'cmd' or '_' not in name else 'cat-' + name.split('_', 1)[1])
    os.makedirs(cat_dir, exist_ok=True)
    entries, stats = [], {}
    for m in mods:
        t0 = time.time()
        stem = os.path.basename(m).lower()
        # a side-by-side assembly's DLL (work/rebased-shell/sxs/<assembly>/comctl32.dll) beside the
        # system one of the same name: its own catalog and output directory
        par = os.path.dirname(m)
        if os.path.basename(os.path.dirname(par)).lower() == 'sxs':
            stem = os.path.basename(par).lower().replace('.', '_') + '_' + stem
        cat = os.path.join(cat_dir, stem + '.functions.json')
        # work/seeds/<file>.json: functions a run found unresolved (ICALL), re-catalogued when newer
        # (a set with its own catalogs has its own seeds: work/seeds-lx for the _lx sets, started as a copy)
        seeds = os.path.join(ROOT, 'work', 'seeds-lx' if cat_dir.endswith('cat-lx') else 'seeds', stem + '.json')
        seeds = seeds if os.path.exists(seeds) else None
        # a module rebased since its catalog (ulib moved off user32's base: 0 functions lifted, silently)
        moved = os.path.exists(cat) and json.load(open(cat)).get('image_base') != \
            __import__('pefile').PE(m, fast_load=True).OPTIONAL_HEADER.ImageBase
        if moved or not os.path.exists(cat) or (seeds and os.path.getmtime(seeds) > os.path.getmtime(cat)):
            with open(cat[:-15] + '.catalog.log', 'w') as log:
                if subprocess.run([sys.executable, os.path.join(TOOLS, 'disasm', 'disasm32.py'), m, '-o', cat]
                                  + (['--seed-functions', seeds] if seeds else []),
                                  stdout=log, stderr=subprocess.STDOUT).returncode:
                    sys.exit('disasm32 failed on %s, see %s' % (m, log.name))
        st, ent = lift_image(m, cat, os.path.join(out, stem.split('.')[0]))
        entries += ent
        stats[stem] = st
        print('  %s: %d functions, errors %d, unimplemented %d, %.0fs'
              % (stem, len(ent), st['errors'], sum(st['unimplemented'].values()), time.time() - t0))
    entries = sorted(set(entries))
    json.dump(stats, open(os.path.join(ROOT, 'work', name + '.lift_stats.json'), 'w'), indent=1)
    put(os.path.join(out, 'recomp_funcs.h'),
        '/* AUTO-GENERATED by tools/lift.py */\n#pragma once\n#include <stdint.h>\n\n'
        + ''.join('void sub_%08X(void);\n' % a for a in entries))
    put(os.path.join(out, 'recomp_dispatch.c'),
        '/* AUTO-GENERATED by tools/lift.py */\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n\n'
        'const recomp_dispatch_entry_t recomp_dispatch_table[] = {\n'
        + ''.join('    { 0x%08Xu, sub_%08X },\n' % (a, a) for a in entries)
        + '};\nconst uint32_t recomp_dispatch_count = %d;\n' % len(entries))
    print('%s: %d functions in the dispatch table' % (name, len(entries)))


if __name__ == '__main__':
    main()
